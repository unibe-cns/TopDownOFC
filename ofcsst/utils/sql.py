"""Thin sqlite3 helpers for the result databases.

Results are stored in wide tables: a few columns identifying the condition and
the hyperparameters, followed by one column per trial. `get_data_type` maps a
column name to its declared SQLite type, including the per-trial series columns
that are generated by name prefix.
"""
import sqlite3
from typing import Sequence
from pathlib import Path
from os.path import dirname
from ofcsst.utils import keys

DATA_TYPE_REAL = "REAL"
DATA_TYPE_INT = "INT"


def connect(db_path: Path) -> sqlite3.Connection:
    Path(dirname(db_path)).mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(db_path)
    return conn


def disconnect(conn: sqlite3.Connection) -> None:
    conn.close()


# Exact column name -> SQLite type. Columns not listed here are per-trial
# series (e.g. "performance_0", "gain_412") and are matched by prefix below.
_COLUMN_TYPES: dict[str, str] = {
    keys.NR_DISTRACTOR: DATA_TYPE_INT,
    keys.NR_SIGNAL: DATA_TYPE_INT,
    keys.SEED: DATA_TYPE_INT,
    keys.DISTRACTOR_GAIN: DATA_TYPE_REAL,
    keys.SIGNAL_GAIN: DATA_TYPE_REAL,
    keys.LEARNING_RATE_PG: DATA_TYPE_REAL,
    keys.LEARNING_RATE_Q: DATA_TYPE_REAL,
    keys.LEARNING_RATE_V: DATA_TYPE_REAL,
    keys.LEARNING_RATE_SD: DATA_TYPE_REAL,
    keys.SST_W: DATA_TYPE_REAL,
    keys.SST_B: DATA_TYPE_REAL,
    keys.OFC_K_IN: DATA_TYPE_REAL,
    keys.RW_K: DATA_TYPE_REAL,
    keys.EXPERT_FRAC: DATA_TYPE_REAL,
    keys.EXPERT_TIME: DATA_TYPE_REAL,
}

# Keys whose name appears inside every column of a per-trial series.
_SERIES_KEYS = (
    keys.LOSS,
    keys.PERFORMANCE,
    keys.AGENT_GAIN,
    keys.AGENT_POLICY_WEIGHT,
    keys.OFC_ACTIVITY,
)


def get_data_type(column: str) -> str:
    """Return the SQLite type to declare for a result-database column."""
    if column in _COLUMN_TYPES:
        return _COLUMN_TYPES[column]
    if any(series_key in column for series_key in _SERIES_KEYS):
        return DATA_TYPE_REAL
    raise NotImplementedError(column)


def make_table(
    conn: sqlite3.Connection,
    table_name: str,
    col_names: list[str],
    verbose: bool = False,
) -> None:
    cur = conn.cursor()
    cur.execute(
        "SELECT count(name) FROM sqlite_master WHERE type='table' AND name='"
        + table_name
        + "';"
    )
    if cur.fetchone()[0] != 1:
        cmd = "CREATE TABLE {} (".format(table_name)
        cmd += ", ".join([cn + " " + get_data_type(cn) for cn in col_names])
        cmd += ");"
        conn.execute(cmd)
        if verbose:
            print("Table {} was created".format(table_name))
    elif verbose:
        print("Table {} already exists".format(table_name))
    conn.commit()
    cur.close()


def drop_table(conn: sqlite3.Connection, table_name: str, verbose: bool = True) -> None:
    cur = conn.cursor()
    cur.execute(
        "SELECT count(name) FROM sqlite_master WHERE type='table' AND name='"
        + table_name
        + "';"
    )
    if cur.fetchone()[0] == 1:
        cmd = "DROP TABLE {};".format(table_name)
        conn.execute(cmd)
        if verbose:
            print("Table {} was dropped".format(table_name))

    elif verbose:
        print(
            "Table {} doesn't exist and could therefore not be dropped".format(
                table_name
            )
        )


def get_insert_cmds(table: str, values: dict):
    columns = ",".join(values.keys())
    placeholders = ", ".join("?" * len(values.values()))
    insert_cmd = "INSERT INTO {}({}) VALUES({})".format(table, columns, placeholders)
    insert_values = tuple(values.values())

    return insert_cmd, insert_values


def insert(
    db_path: Path,
    table: str,
    unique_values: dict,
    unique_cols: list[str],
    outcome_values: dict,
    outcome_cols: list[str],
) -> None:
    # Make sure all the required values are defined
    assert all(c in unique_values.keys() for c in unique_cols)
    assert all(c in outcome_values.keys() for c in outcome_cols)

    # Prepare the sqlite commands before executing them to reduce the interaction time with the database
    insert_cmd, insert_values = get_insert_cmds(
        table=table, values={**unique_values, **outcome_values}
    )

    # Connect with the database
    conn = connect(db_path=db_path)
    cur = conn.cursor()

    cur.execute(insert_cmd, insert_values)

    # Commit changes and disconnect
    conn.commit()
    cur.close()
    disconnect(conn=conn)


def get_where_cmd(unique_cols: list[str]) -> str:
    if len(unique_cols) == 0:
        return ""
    else:
        return "WHERE (" + " = ? AND ".join(unique_cols) + " = ?)"


def get_count_cmd(
    table: str, unique_values: dict, unique_cols: list[str]
) -> tuple[str, tuple]:
    where_cmd = get_where_cmd(unique_cols=unique_cols)
    exists_cmd = "SELECT count(*) FROM {} {};".format(table, where_cmd)
    exists_values = tuple(unique_values[k] for k in unique_cols)
    return exists_cmd, exists_values


def count_rows(
    cur: sqlite3.Cursor, table: str, unique_values: dict, unique_cols: list
) -> int:
    # Check if where specifications are required
    if bool(unique_values):
        # Write the command out that does the query
        count_cmd, where_values = get_count_cmd(
            table=table, unique_values=unique_values, unique_cols=unique_cols
        )

        # Execute query
        cur.execute(count_cmd, where_values)

    else:
        cur.execute(f"SELECT count(*) FROM {table};")

    return cur.fetchone()[0]


def row_exists(
    cur: sqlite3.Cursor, table: str, unique_values: dict, unique_cols: list
) -> bool:
    where_cmd = get_where_cmd(unique_cols=unique_cols)
    exists_cmd = f"SELECT EXISTS(SELECT 1 FROM {table} {where_cmd});"
    exists_values = tuple(unique_values[k] for k in unique_cols)
    cur.execute(exists_cmd, exists_values)
    return bool(cur.fetchone()[0])


def get_insert_cmd(table: str, col_keys: list[str]) -> str:
    columns = ",".join(col_keys)
    placeholders = ", ".join("?" * len(col_keys))
    insert_cmd = "INSERT INTO {}({}) VALUES({})".format(table, columns, placeholders)
    return insert_cmd


def select(db_path: Path, table: str, get_cols: Sequence[str]) -> list[tuple]:
    conn = connect(db_path=db_path)
    cur = conn.cursor()
    cur.execute(f"SELECT {', '.join(get_cols)} FROM {table}")
    rows = cur.fetchall()
    cur.close()
    disconnect(conn=conn)
    return rows


def select_where_cmd(
    table: str, get_cols: Sequence[str], where_values: dict
) -> tuple[str, tuple]:
    where_keys = [str(k) for k in where_values.keys()]
    cmd = f"SELECT {', '.join(get_cols)} FROM {table} {get_where_cmd(unique_cols=where_keys)}"
    where_tuple = tuple(where_values[k] for k in where_keys)
    return cmd, where_tuple


def select_where(
    db_path: Path, table: str, get_cols: Sequence[str], where_values: dict
) -> list[tuple]:
    if where_values is None or len(where_values) == 0:
        return select(db_path=db_path, table=table, get_cols=get_cols)
    else:
        conn = connect(db_path=db_path)
        cur = conn.cursor()
        cmd, where_tuple = select_where_cmd(
            table=table, get_cols=get_cols, where_values=where_values
        )
        try:
            cur.execute(cmd, where_tuple)
        except sqlite3.OperationalError as e:
            print(f"Database: {db_path}")
            raise sqlite3.OperationalError(e)
        rows = cur.fetchall()
        cur.close()
        disconnect(conn=conn)
        return rows


def get_max(
    db_path: Path,
    table: str,
    max_col: str,
    group_cols: Sequence[str],
    select_cols: Sequence[str],
    unique_values: dict | None = None,
    maxmin: bool = True,
) -> list[tuple]:
    if maxmin:
        maxmin_str = "max"
    else:
        maxmin_str = "min"
    grouping = len(group_cols) >= 1
    group_by = ", ".join(group_cols)
    select_cmd = ", ".join(select_cols)
    conn = connect(db_path=db_path)
    cur = conn.cursor()
    if grouping:
        cur.execute(
            f"SELECT {select_cmd}, {maxmin_str}({max_col}) FROM {table} GROUP BY {group_by};"
        )
    elif unique_values is not None:
        where_keys = [str(k) for k in unique_values.keys()]
        cmd = f"SELECT {select_cmd}, {maxmin_str}({max_col}) FROM {table} {get_where_cmd(unique_cols=where_keys)};"
        where_tuple = tuple(unique_values[k] for k in where_keys)
        cur.execute(cmd, where_tuple)
    else:
        cur.execute(f"SELECT {select_cmd}, {maxmin_str}({max_col}) FROM {table};")
    max_rows = [r[:-1] for r in cur.fetchall()]
    cur.close()
    disconnect(conn=conn)
    return max_rows
